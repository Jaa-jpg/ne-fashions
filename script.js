/* ---------------- ADD TO CART ---------------- */

function addCurrentToCart() {

  if (!currentProduct) return;

  if (!selectedSize) {

    alert("Please select a size.");

    return;
  }

  const color =
    getCurrentColor();

  const existing =
    cart.find(item =>
      item.productId === currentProduct.id &&
      item.color === color.name &&
      item.size === selectedSize
    );

  if (existing) {

    existing.quantity += 1;

  } else {

    cart.push({

      productId: currentProduct.id,

      name: currentProduct.name,

      price: currentProduct.price,

      color: color.name,

      size: selectedSize,

      image: color.images[0],

      quantity: 1

    });

  }

  saveCart();

  updateCartCount();

  renderCart();

  updateDetailCartButton();
}


/* ---------------- PRODUCT PAGE CART BUTTON ---------------- */

function updateDetailCartButton() {

  if (!currentProduct) return;

  const button =
    document.getElementById("detailAddToCartBtn") ||
    document.querySelector(
      'button[onclick*="addCurrentToCart"]'
    );

  if (!button) return;

  if (!selectedSize) {

    button.innerHTML = "ADD TO CART";
    button.classList.remove("added");

    return;
  }

  const color = getCurrentColor();

  const cartItem = cart.find(item =>
    item.productId === currentProduct.id &&
    item.color === color.name &&
    item.size === selectedSize
  );

  /* Product is already in cart */
  if (cartItem) {

    button.innerHTML = `
      <span class="cart-qty-minus"
            onclick="event.stopPropagation(); changeCurrentProductQuantity(-1)">
        −
      </span>

      <span class="cart-qty-number">
        ${cartItem.quantity}
      </span>

      <span class="cart-qty-plus"
            onclick="event.stopPropagation(); changeCurrentProductQuantity(1)">
        +
      </span>
    `;

    button.classList.add("added");

  } else {

    button.innerHTML = "ADD TO CART";
    button.classList.remove("added");

  }
}
function changeCurrentProductQuantity(change) {

  if (!currentProduct || !selectedSize) return;

  const color = getCurrentColor();

  const cartItem = cart.find(item =>
    item.productId === currentProduct.id &&
    item.color === color.name &&
    item.size === selectedSize
  );

  if (!cartItem) return;

  cartItem.quantity += change;

  if (cartItem.quantity <= 0) {
    cart = cart.filter(item => item !== cartItem);
  }

  saveCart();
  updateCartCount();
  renderCart();
  updateDetailCartButton();
}

