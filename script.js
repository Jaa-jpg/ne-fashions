/* ---------------- RENDER CART ---------------- */

function renderCart() {

  const container =
    document.getElementById("cartItems");

  if (!container) return;

  if (!cart.length) {

    container.innerHTML = `

      <div class="empty-message">
        Your cart is empty.
      </div>

    `;

    document.getElementById("cartTotal").textContent =
      "₹0";

    return;
  }

  container.innerHTML =
    cart.map((item, index) => `

      <div class="cart-item">

        <img
          src="${item.image}"
          alt="${item.name}"
          onerror="handleImageError(this)"
        >

        <div class="cart-item-info">

          <h3>
            ${item.name}
          </h3>

          <div class="cart-meta">
            Color: ${item.color}<br>
            Size: ${item.size}
          </div>

          <div class="cart-item-price">
            ${money(item.price)}
          </div>

          <div class="quantity">

            <button
              onclick="changeQuantity(${index}, -1)"
            >
              −
            </button>

            <span>
              ${item.quantity}
            </span>

            <button
              onclick="changeQuantity(${index}, 1)"
            >
              +
            </button>

          </div>

          <button
            class="remove-item"
            onclick="removeCartItem(${index})"
          >
            REMOVE
          </button>

        </div>

      </div>

    `).join("");

  const total =
    cart.reduce(
      (sum, item) =>
        sum + item.price * item.quantity,
      0
    );

  document.getElementById("cartTotal").textContent =
    money(total);
}


/* ---------------- CHANGE QUANTITY ---------------- */

function changeQuantity(index, change) {

  if (!cart[index]) return;

  cart[index].quantity += change;

  if (cart[index].quantity <= 0) {

    cart.splice(index, 1);

  }

  saveCart();

  renderCart();

  updateCartCount();

  updateDetailCartButton();
}


/* ---------------- REMOVE CART ITEM ---------------- */

function removeCartItem(index) {

  if (!cart[index]) return;

  cart.splice(index, 1);

  saveCart();

  renderCart();

  updateCartCount();

  updateDetailCartButton();
}


