/* ---------------- WISHLIST HELPERS ---------------- */

function getWishlistItem(productId, colorName = null) {
  return wishlist.find(item =>
    item.productId === productId &&
    (!colorName || item.color === colorName)
  );
}

function isProductWishlisted(productId) {
  return wishlist.some(item =>
    item.productId === productId
  );
}


/* ---------------- WISHLIST ADD ---------------- */

function toggleWishlist(productId) {
  const product = products.find(p => p.id === productId);
  if (!product) return;

  /* Already wishlisted → REMOVE */
  const existing = wishlist.find(item =>
    item.productId === productId
  );

  if (existing) {
    wishlist = wishlist.filter(item =>
      item.productId !== productId
    );

    saveWishlist();
    renderProducts();
    updateWishlistCount();
    renderWishlist();

    if (currentProduct && currentProduct.id === productId) {
      updateDetailWishlistButton();
    }

    return;
  }

  /* Not wishlisted → open product and select size */
  if (!currentProduct || currentProduct.id !== productId) {
    openProduct(productId, 0);

    setTimeout(() => {
      alert("Please select a size first.");
    }, 100);

    return;
  }

  if (!selectedSize) {
    alert("Please select a size first.");
    return;
  }

  const color = getCurrentColor();

  wishlist.push({
    productId: product.id,
    color: color.name,
    size: selectedSize
  });

  saveWishlist();
  renderProducts();
  updateWishlistCount();
  updateDetailWishlistButton();
  renderWishlist();
}


/* ---------------- DETAIL WISHLIST ---------------- */

function toggleCurrentWishlist() {

  if (!currentProduct) return;

  toggleWishlist(currentProduct.id);
}


/* ---------------- WISHLIST BUTTON ---------------- */

function updateDetailWishlistButton() {

  const button =
    document.getElementById("detailWishlistBtn");

  if (!button || !currentProduct) return;

  const color = getCurrentColor();

  const item =
    getWishlistItem(
      currentProduct.id,
      color.name
    );

  if (item) {

    button.textContent = "♥";

    button.classList.add("active");

    button.setAttribute(
      "aria-label",
      `Wishlisted • Size ${item.size}`
    );

    button.title =
      `Wishlist • Size ${item.size}`;

  } else {

    button.textContent = "♡";

    button.classList.remove("active");

    button.setAttribute(
      "aria-label",
      "Add to wishlist"
    );

    button.title =
      "Select size and add to wishlist";

  }
}


/* ---------------- WISHLIST COUNT ---------------- */

